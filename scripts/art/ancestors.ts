// The portraits on the family wall (SPEC §22.10).
//
//   npm run art:ancestors
//
// Every generation looks the same in life, so every ancestor's portrait is the
// same picture: the front idle frame's head and shoulders, put through the
// same filter as the framed picture (scripts/art/filter.ts) — on cream paper
// where the sprite is transparent, median-cut to a few colours. The wall hangs
// it at four sizes, and each is filtered from the sprite in its own right:
// shrinking the largest on the canvas would turn pixel art to mush.
//
// A generation that died a Sage hangs in a second set: the same frame with
// the beard composited where the room hangs it and the frame's own mouth kept
// in front of it, then the same filter. It is
// generated, never drawn, so it follows the beard wherever the beard goes.
//
// One palette serves every size of both sets, taken from the two largest
// together and with the beard's white pinned into it, so a portrait keeps its
// colours as it shrinks, the beard stays white against the paper, and the
// room can fade all of them toward sepia with one blend per slot.

import { readFileSync, writeFileSync } from "node:fs";
import { PNG } from "pngjs";
import { downscale, letterRows, paletteEntries, quantize, toPalette, type RGB } from "./filter.ts";
import { SPRITE_FRAMES, SPRITE_MOUTHS, SPRITE_SHEET_URL } from "../../src/game/atlas.generated.ts";
import { overlayOffset } from "../../src/game/engine/placement.ts";
import { HEAD_ANCHORS } from "../../src/game/scene/head.ts";

const SHEET = new URL(`../../public${SPRITE_SHEET_URL}`, import.meta.url);
const GENERATED = new URL("../../src/game/scene/ancestors.generated.ts", import.meta.url);
const CONTACT = new URL("./ancestors-contact.png", import.meta.url);

/** The frame the portrait is taken from, and how much of it: a square from the top — head and shoulders. */
const FRAME = SPRITE_FRAMES.idleFront1;
const CROP = { x: 0, y: 0, w: FRAME.w, h: FRAME.w };
/** The art sizes the wall's slots want, largest first (SPEC §22.10). */
const SIZES = [32, 24, 20, 16] as const;
const COLOURS = 8;
/** Flat pixel art has no thin strokes to protect; a gentle bias keeps the outline from washing out. */
const INK_BIAS = 2;
/** The beard's own colour (SPEC §21.9), kept apart from the paper and the belly it hangs over. */
const BEARD_WHITE: RGB = [255, 255, 255];
/** What shows where the sprite is transparent: the photograph's paper. */
const PAPER: RGB = [236, 226, 200];

/** The beard, at the anchor the room hangs it from on this frame (SPEC §10.5). */
const BEARD = SPRITE_FRAMES.sageBeard;
const BEARD_AT = overlayOffset(FRAME, BEARD, HEAD_ANCHORS.idleFront1!.beard.x, HEAD_ANCHORS.idleFront1!.beard.y);

/** The frame's mouth, in the frame's own pixels: the beard never covers it (SPEC §21.9). */
const MOUTH = SPRITE_MOUTHS.idleFront1!;

const sheet = PNG.sync.read(readFileSync(SHEET));
/** A sheet pixel, or null where it is transparent. */
const sheetAt = (x: number, y: number): RGB | null => {
  const index = (y * sheet.width + x) << 2;
  if (sheet.data[index + 3] === 0) return null;
  return [sheet.data[index]!, sheet.data[index + 1]!, sheet.data[index + 2]!];
};
const plainAt = (x: number, y: number): RGB => sheetAt(FRAME.x + x, FRAME.y + y) ?? PAPER;
const sageAt = (x: number, y: number): RGB => {
  if (sheetAt(MOUTH.x + x, MOUTH.y + y)) return plainAt(x, y);
  const bx = x - BEARD_AT.x;
  const by = y - BEARD_AT.y;
  const inBeard = bx >= 0 && by >= 0 && bx < BEARD.w && by < BEARD.h;
  return (inBeard ? sheetAt(BEARD.x + bx, BEARD.y + by) : null) ?? plainAt(x, y);
};

const plainGrids = SIZES.map((size) => downscale(plainAt, CROP, size, size, INK_BIAS));
const sageGrids = SIZES.map((size) => downscale(sageAt, CROP, size, size, INK_BIAS));
const { palette } = quantize([...plainGrids[0]!, ...sageGrids[0]!], COLOURS, [BEARD_WHITE]);
const picturesOf = (grids: RGB[][][]) => SIZES.map((size, index) => ({ size, indices: toPalette(grids[index]!, palette) }));
const pictures = picturesOf(plainGrids);
const sagePictures = picturesOf(sageGrids);

const emitPictures = (set: typeof pictures): string =>
  set
    .map(
      ({ size, indices }) => `  {
    size: ${size},
    rows: [
${letterRows(indices)
  .map((row) => `      "${row}",`)
  .join("\n")}
    ],
  },`,
    )
    .join("\n");

writeFileSync(
  GENERATED,
  `// GENERATED by scripts/art/ancestors.ts from the sprite sheet's idleFront1 frame.
// Do not edit: re-run \`npm run art:ancestors\` instead (SPEC §22.10).
//
// The same head and shoulders at ${SIZES.join(", ")} pixels, plain and bearded,
// ${palette.length} colours shared across both sets and every size, one letter per pixel,
// ordered lightest to darkest.

/** Letter to colour, lightest first. */
export const ANCESTOR_PALETTE: Readonly<Record<string, readonly [number, number, number]>> = {
${paletteEntries(palette)}
};

/** The portrait at each size the wall hangs it, largest first. */
export const ANCESTOR_PICTURES: readonly { size: number; rows: readonly string[] }[] = [
${emitPictures(pictures)}
];

/** The same, for a generation that died a Sage: the beard as the room hangs it. */
export const SAGE_ANCESTOR_PICTURES: readonly { size: number; rows: readonly string[] }[] = [
${emitPictures(sagePictures)}
];
`,
);

// A contact print at 6x, every size side by side, plain above bearded, for looking at.
const SCALE = 6;
const GAP = 4;
const contact = new PNG({
  width: (SIZES.reduce((sum, size) => sum + size, 0) + GAP * (SIZES.length + 1)) * SCALE,
  height: (SIZES[0] * 2 + GAP * 3) * SCALE,
});
contact.data.fill(255);
[pictures, sagePictures].forEach((set, row) => {
  const top = GAP + row * (SIZES[0] + GAP);
  let left = GAP;
  for (const { size, indices } of set) {
    for (let y = 0; y < size * SCALE; y++) {
      for (let x = 0; x < size * SCALE; x++) {
        const colour = palette[indices[Math.floor(y / SCALE)]![Math.floor(x / SCALE)]!]!;
        const index = ((y + top * SCALE) * contact.width + x + left * SCALE) << 2;
        contact.data[index] = colour[0];
        contact.data[index + 1] = colour[1];
        contact.data[index + 2] = colour[2];
        contact.data[index + 3] = 255;
      }
    }
    left += size + GAP;
  }
});
writeFileSync(CONTACT, PNG.sync.write(contact));
console.log(`ancestors: ${SIZES.join("/")}px, plain and Sage, at ${palette.length} colours → src/game/scene/ancestors.generated.ts + scripts/art/ancestors-contact.png`);
