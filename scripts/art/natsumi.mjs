// Natsumi's frames (SPEC §13.3.2), as editable letter grids. Edit a grid, run
// `npm run art:natsumi`, then `npm run atlas` to repack the sheet.
//
// The style is Jingles' own: a 1px black outline, flat fills, and features
// only a pixel or two across — her eyes are two pixels curving upward. The
// colours come from the reference art: yellow skin, lavender hair that runs
// through pink to blonde at the very tips, and a plain dress with a ribbon at
// the throat and shoes dyed to match it.
//
// Four states, each in two variants — bare-headed and under the witch hat:
//
//   away   turned around, all hair     Makoto may run
//   turn   mid-swing, one eye clear    he may run, briefly
//   watch  facing him                  he must not move
//   grin   she has caught him          he is back at the start
//
// A head grid is 19 rows; the body below the neck is shared, so only her face
// acts. The hat is a cone and a brim stamped over the head's top rows, which
// is what makes the hatted frames taller.

