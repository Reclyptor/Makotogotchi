/** How many rows of crown the brim covers. */
const HAT_COVERS = 8;

const rowsOf = (grid) => grid.trim().split("\n");

// Her hair is lavender for most of each lock, then pink, then blonde at the
// tip. Grading it here rather than in the grids keeps the three bands aligned
// however long the lock ends up.
const LOCK_COLUMNS = [4, 5, 24, 25];
const PINK_ROWS = 2;
const GOLD_ROWS = 2;
const gradeLocks = (rows) => {
  const lockRows = rows.flatMap((row, index) => (LOCK_COLUMNS.some((c) => "HKY".includes(row[c] ?? ".")) ? [index] : []));
  const goldFrom = lockRows.length - GOLD_ROWS;
  const pinkFrom = goldFrom - PINK_ROWS;
  return rows.map((row, index) => {
    const position = lockRows.indexOf(index);
    if (position < 0) return row;
    const letter = position >= goldFrom ? "Y" : position >= pinkFrom ? "K" : "H";
    const chars = [...row];
    for (const c of LOCK_COLUMNS) if ("HKY".includes(chars[c])) chars[c] = letter;
    return chars.join("");
  });
};

const frames = {};
for (const [state, head] of Object.entries(HEADS)) {
  const body = rowsOf(dress(state !== "Away"));
  frames[`natsumi${state}`] = gradeLocks([...rowsOf(head), ...body]);
  frames[`natsumiHat${state}`] = gradeLocks([...rowsOf(HAT), ...rowsOf(head).slice(HAT_COVERS), ...body]);
}

const write = (name, rows) => {
  const width = rows[0].length;
  for (const [index, row] of rows.entries()) {
    if (row.length !== width) throw new Error(`${name}: row ${index} is ${row.length} wide, expected ${width}`);
  }
  const png = new PNG({ width, height: rows.length });
  rows.forEach((row, y) => {
    for (let x = 0; x < width; x += 1) {
      const letter = row[x];
      const rgba = letter === "." ? [0, 0, 0, 0] : PALETTE[letter];
      if (!rgba) throw new Error(`${name}: unknown palette letter "${letter}" at ${x},${y}`);
      const i = (y * width + x) * 4;
      [png.data[i], png.data[i + 1], png.data[i + 2], png.data[i + 3]] = rgba;
    }
  });
  mkdirSync(OUT, { recursive: true });
  writeFileSync(new URL(`${name}@1x.png`, OUT), PNG.sync.write(png));
  return `${name} ${width}x${rows.length}`;
};

