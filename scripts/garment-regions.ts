// Finds the body a worn garment hangs on, on every pet frame that can wear one
// (SPEC §22.12), and writes it to src/game/scene/garment.generated.ts.
//
//   npm run garment-regions
//
// Run it after `npm run atlas` and `npm run head-anchors`: it reads the packed
// sheet and the beard anchors, which put the neckline two rows under the
// mouth. Nothing is placed by hand per frame; the only hand-set facts are the
// frames that sit, and the frames that wear no garment at all.

import { readFileSync, writeFileSync } from "node:fs";
import { PNG } from "pngjs";
import { SPRITE_FRAMES, SPRITE_MASKS, SPRITE_SHEET_URL, type FrameName } from "../src/game/atlas.generated.ts";
import { BASE_CLIPS, IDLE_FLOURISH_CLIPS, ONE_SHOT_CLIPS, WALK_CLIP } from "../src/game/anim/clips.ts";
import { HEAD_ANCHORS } from "../src/game/scene/head.ts";
import type { GarmentBox } from "../src/game/scene/garment.ts";
import { rasterOf } from "./head-parts.ts";
import { regionOf } from "./garment-parts.ts";

const SHEET = new URL(`../public${SPRITE_SHEET_URL}`, import.meta.url);
const GENERATED = new URL("../src/game/scene/garment.generated.ts", import.meta.url);

/** Frames with a body but no garment: in bed under a nightcap, under the dust bath's cloud, or under the ice pack. */
const BARE: readonly FrameName[] = ["dustbath1", "dustbath2", "dustbath3", "sick1", "sick2"];
/** Poses sitting with their paws in the lap, which no outline tells apart from a standing one. */
const SEATED: readonly FrameName[] = ["meditate1", "meditate2"];

const sheet = PNG.sync.read(readFileSync(SHEET));

const petFrames = (): FrameName[] => {
  const names = new Set<FrameName>();
  for (const clip of [...Object.values(BASE_CLIPS), ...Object.values(ONE_SHOT_CLIPS), ...IDLE_FLOURISH_CLIPS, WALK_CLIP]) {
    for (const frame of clip.frames) names.add(frame);
  }
  return [...names].sort();
};

const regions = petFrames().flatMap((name) => {
  const anchor = HEAD_ANCHORS[name];
  if (!anchor || anchor.nightcap || BARE.includes(name)) return [];
  const frame = SPRITE_FRAMES[name];
  const mask = SPRITE_MASKS[name];
  // The beard hangs from the mouth's top row, so its top edge is where the mouth starts.
  const mouthTop = frame.h + anchor.beard.y - SPRITE_FRAMES.sageBeard.h;
  const region = regionOf(rasterOf(sheet, frame), mask ? rasterOf(sheet, mask) : null, mouthTop, SEATED.includes(name));
  return [[name, region] as const];
});

const lines = [
  "// GENERATED by scripts/garment-regions.ts — do not edit by hand. Re-run",
  "// `npm run garment-regions` after `npm run atlas` and `npm run head-anchors`.",
  "",
  'import type { FrameName } from "../atlas.generated";',
  'import type { GarmentRegion } from "./garment";',
  "",
  "/** The body a worn garment hangs on, per pet frame that can wear one (SPEC §22.12). */",
  "export const GARMENT_REGIONS: Partial<Record<FrameName, GarmentRegion>> = {",
  ...regions.map(([name, r]) => {
    const box = (b: GarmentBox): string => `{ x0: ${b.x0}, x1: ${b.x1}, y0: ${b.y0}, y1: ${b.y1} }`;
    const paws = r.paws.map((p) => `{ paw: ${box(p.paw)}, cuff: ${p.cuff ? box(p.cuff) : "null"} }`).join(", ");
    const rows = r.rows.map((row) => `"${row}"`).join(", ");
    const head = r.head.map((row) => `"${row}"`).join(", ");
    const grid = `ox: ${r.ox}, oy: ${r.oy}, w: ${r.w}, h: ${r.h}`;
    return `  ${name}: { face: "${r.face}", ${grid}, neck: ${r.neck}, bottom: ${r.bottom}, col0: ${r.col0}, paws: [${paws}], head: [${head}], rows: [${rows}] },`;
  }),
  "};",
  "",
];
writeFileSync(GENERATED, lines.join("\n"));
console.log(`garment-regions: ${regions.length} frames → src/game/scene/garment.generated.ts`);
for (const [name, r] of regions) console.log(`${name}: ${r.face}, neck row ${r.neck}, bottom ${r.bottom}`);
