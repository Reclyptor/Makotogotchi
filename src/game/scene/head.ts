// Where things are worn on each pet frame (SPEC §10.5). The art's head is not
// in the same place from one frame to the next — the side view's ear dip is
// fourteen pixels left of where the front view's is — so anything drawn at
// one fixed spot lands on an ear as often as between them.
//
// Each entry is in the room's head space: `x` from the frame's bottom-centre
// as the atlas snaps it, `y` from the frame's bottom edge.
//
//   • `x`, `y` — the hat anchor: midway between the pink inner ears, on the
//     head outline at the bottom of the dip between them.
//   • `brows` — where an elder's brow tufts stand (bottom-centre): midway
//     between the eyes, one art pixel above them. Not the hat anchor: the dip
//     is the top of the skull, and tufts hung from it stood above the outline
//     like a second pair of ears.
//   • `beard` — where a sage's beard hangs (bottom-centre, like the brows):
//     centred on the mouth, its top row the mouth's top row, so the moustache
//     covers the mouth and the beard falls down the chest.
//   • `cane` — where a sage's cane stands (bottom-centre, like the beard): its
//     ferrule on the floor beside the feet, its shaft running up through the
//     near paw and its knob resting on top of it. `null` on every frame whose
//     paws are busy — eating, at tea, gaming, grooming, bathing, meditating,
//     asleep, dead — and on the free-pawed frames that only ever play beside
//     those, so the cane never pops in and out mid-clip. `behind` would mark a
//     pose that holds it behind the body; no frame does yet.
//   • `nightcap` — the art already wears a hat here, so no cosmetic goes on
//     top of it.
//
// `null` is a frame with no ears to wear anything on: the egg, the
// gravestone, the medicine, the pet inside the cloning tank.
//
// Generated by `npm run head-anchors` and reviewed on its contact sheet; the
// null frames are hand-set, as are the dust bath's second and third frames
// and groom1, where the dust or a paw hides an eye or the mouth. The cane's
// points come from the script's hand-set grip table, frame by frame.

